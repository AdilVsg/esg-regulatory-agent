"""
Score the RAG route with RAGAS, reading the answers already generated by
eval/generate_answers.py. No call to the agent is made here: generation and
scoring are deliberately separated so that a scoring failure, on a quota or a
parsing error, never costs generation quota a second time.

Only Q1-Q8 are scored. The context metrics are meaningless on the web-search
route, whose contexts come from Tavily and are not controlled, and on the
refusal route, which has no context at all. Routing is measured separately by
eval/router_eval.py.

The judge is Gemini rather than the OpenAI default, and the embeddings needed by
answer_relevancy are the local bge-small already used by the retriever, so no
embedding API is called and no quota is spent on them.

Usage, from the repo root:

    $env:GEMINI_API_KEY = "..."
    python -m eval.run_ragas

    python -m eval.run_ragas --only Q3,Q6      # rescore a subset after a failure

Expect 60 to 100 judge calls for the 8 questions and a run of 10 to 20 minutes.
A question whose score comes back NaN failed rather than scored zero; rerun it
with --only rather than reading it as a bad result.
"""
import argparse
import json
import os
from datetime import datetime, timezone
from pathlib import Path

from langchain_google_genai import ChatGoogleGenerativeAI
from langchain_huggingface import HuggingFaceEmbeddings
from ragas import EvaluationDataset, evaluate
from ragas.embeddings import LangchainEmbeddingsWrapper
from ragas.llms import LangchainLLMWrapper
from ragas.metrics import (
    answer_relevancy,
    context_precision,
    context_recall,
    faithfulness,
)
from ragas.run_config import RunConfig

OUTPUTS_PATH = Path("eval/rag_outputs.jsonl")
QUESTIONS_PATH = Path("eval/test_questions.yaml")
RESULTS_PATH = Path("eval/ragas_results.json")

SCORED_CATEGORIES = {"retrieval", "cross_doc"}

# The judge is a deliberate choice, not a default: a Flash-Lite model keeps the
# run inside the free tier, and the same model family already serves the agent.
JUDGE_MODEL = os.environ.get("RAGAS_JUDGE_MODEL", "gemini-3.5-flash-lite")
EMBEDDING_MODEL = "BAAI/bge-small-en-v1.5"

METRICS = [faithfulness, answer_relevancy, context_precision, context_recall]


def load_dataset(only: set[str] | None):
    import yaml

    with open(QUESTIONS_PATH, encoding="utf-8") as f:
        questions = {q["id"]: q for q in yaml.safe_load(f)["questions"]}

    if not OUTPUTS_PATH.exists():
        raise SystemExit(f"{OUTPUTS_PATH} absent. Lance d'abord eval.generate_answers.")

    rows, ids = [], []
    with open(OUTPUTS_PATH, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            record = json.loads(line)
            qid = record["id"]

            if record["category"] not in SCORED_CATEGORIES:
                continue
            if only and qid not in only:
                continue

            gold = questions.get(qid, {}).get("gold_answer")
            if not gold:
                print(f"  {qid} ignore : pas de gold_answer dans le YAML.")
                continue
            if not record.get("retrieved_contexts"):
                print(f"  {qid} ignore : aucun contexte recupere.")
                continue

            rows.append(
                {
                    "user_input": record["question"],
                    "response": record["answer"],
                    "retrieved_contexts": record["retrieved_contexts"],
                    "reference": gold.strip(),
                }
            )
            ids.append(qid)

    if not rows:
        raise SystemExit("Aucune question a noter.")
    return EvaluationDataset.from_list(rows), ids


def build_judge():
    api_key = os.environ.get("GEMINI_API_KEY")
    if not api_key:
        raise SystemExit("GEMINI_API_KEY absent de l'environnement.")

    # langchain-google-genai reads GOOGLE_API_KEY, not GEMINI_API_KEY, so the key
    # is passed explicitly rather than relying on the environment.
    llm = ChatGoogleGenerativeAI(
        model=JUDGE_MODEL,
        google_api_key=api_key,
        temperature=0,
        max_retries=6,
    )
    embeddings = HuggingFaceEmbeddings(model_name=EMBEDDING_MODEL)
    return LangchainLLMWrapper(llm), LangchainEmbeddingsWrapper(embeddings)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--only", help="Comma-separated question ids, e.g. Q3,Q6")
    args = parser.parse_args()
    only = {q.strip().upper() for q in args.only.split(",")} if args.only else None

    dataset, ids = load_dataset(only)
    print(f"Notation de {len(ids)} question(s) : {', '.join(ids)}")
    print(f"Juge : {JUDGE_MODEL} | embeddings : {EMBEDDING_MODEL} (local)\n")

    llm, embeddings = build_judge()

    # max_workers=1 keeps the run sequential, well under the free-tier
    # requests-per-minute ceiling. raise_exceptions=False turns a failed metric
    # into NaN for that one cell instead of aborting the whole run, so a single
    # parsing error does not discard the questions already scored.
    result = evaluate(
        dataset=dataset,
        metrics=METRICS,
        llm=llm,
        embeddings=embeddings,
        run_config=RunConfig(max_workers=1, timeout=300, max_retries=6),
        raise_exceptions=False,
        show_progress=True,
    )

    df = result.to_pandas()
    df.insert(0, "id", ids)
    metric_cols = [c for c in df.columns if c in
                   {"faithfulness", "answer_relevancy", "context_precision", "context_recall"}]

    print("\n=== Moyennes globales ===")
    for col in metric_cols:
        mean = df[col].mean(skipna=True)
        n_ok = int(df[col].notna().sum())
        print(f"  {col:<20} {mean:.3f}   ({n_ok}/{len(df)} notees)")

    print("\n=== Par question ===")
    print(df[["id"] + metric_cols].to_string(index=False, float_format="%.3f"))

    failed = [ids[i] for i in range(len(df)) if df[metric_cols].iloc[i].isna().any()]
    if failed:
        print(f"\nIncompletes, a relancer : python -m eval.run_ragas --only {','.join(failed)}")

    payload = {
        "run_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "judge_model": JUDGE_MODEL,
        "embedding_model": EMBEDDING_MODEL,
        "n_questions": len(df),
        "aggregate": {c: (None if df[c].isna().all() else round(float(df[c].mean(skipna=True)), 4))
                      for c in metric_cols},
        "per_question": [
            {"id": ids[i], **{c: (None if df[c].isna().iloc[i] else round(float(df[c].iloc[i]), 4))
                              for c in metric_cols}}
            for i in range(len(df))
        ],
    }
    RESULTS_PATH.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    print(f"\nResultats ecrits dans {RESULTS_PATH}")


if __name__ == "__main__":
    main()